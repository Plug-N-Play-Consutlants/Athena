def _evidence_record(pack: Dict[str, Any], entry: Dict[str, Any], score: int, matched_terms: Sequence[str]) -> Dict[str, Any]:
    manifest = pack.get("manifest", {})
    pack_root = Path(pack.get("pack_root", ""))
    topic_key = entry.get("topic_key")
    return {
        "source_id": manifest.get("source_id") or entry.get("source_id"),
        "source_title": manifest.get("title") or entry.get("source_title"),
        "authority": manifest.get("authority") or entry.get("authority"),
        "document_type": manifest.get("document_type"),
        "season": manifest.get("season"),
        "effective_date": manifest.get("effective_date"),
        "pack_root": str(pack_root),
        "body_file": str(pack_root / pack.get("body_filename", "")),
        "topic_key": topic_key,
        "label": entry.get("label"),
        "category": entry.get("category"),
        "authority_refs": list(entry.get("authority_refs", []) or []),
        "keywords": list(entry.get("keywords", []) or []),
        "summary": _TOPIC_SUMMARIES.get(str(topic_key), entry.get("notes") or "Registered public hockey knowledge topic."),
        "matched_terms": list(matched_terms),
        "score": score,
        "citation_policy": manifest.get("citation_policy") or entry.get("citation_policy"),
        "source_document_present": bool((manifest.get("source_document") or {}).get("present")),
    }


def retrieve_public_hockey_knowledge(
    query: str,
    project_root: Optional[Path] = None,
    mode: str = "public_sports",
    limit: int = 5,
    auto_build: bool = False,
) -> Dict[str, Any]:
    """Retrieve deterministic public hockey evidence for a question/topic.

    The function returns evidence only from compact knowledge packs. It never
    invents facts and does not read source PDFs directly at runtime.
    """
    root = _project_root(project_root)
    query = str(query or "").strip()
    query_tokens = _tokenize(query)
    packs = load_public_hockey_packs(root, auto_build=auto_build)
    candidates: List[Dict[str, Any]] = []

    for pack in packs:
        manifest = pack.get("manifest", {})
        modes = set(manifest.get("modes", []) or [])
        if mode and modes and mode not in modes:
            continue
        topic_index = pack.get("topic_index", {})
        for entry in pack.get("entries", []) or []:
            score, matched_terms = _score_entry(query_tokens, entry, topic_index)
            if score > 0:
                candidates.append(_evidence_record(pack, entry, score, matched_terms))

    candidates.sort(key=lambda item: (-int(item.get("score", 0)), str(item.get("source_id", "")), str(item.get("topic_key", ""))))
    evidence = candidates[: max(1, int(limit or 5))]
    status = "available" if evidence else "no_match" if packs else "missing_packs"
    confidence = 0.0
    if evidence:
        best = max(item.get("score", 0) for item in evidence)
        confidence = min(0.9, 0.45 + (float(best) / 20.0))
    elif packs:
        confidence = 0.25
    else:
        confidence = 0.1

    limitations: List[str] = []
    if not packs:
        limitations.append("Public hockey knowledge packs are not built. Run Tools/build_public_hockey_knowledge_packs.py.")
    if not evidence:
        limitations.append("No compact public hockey knowledge-pack topic matched the question.")
    limitations.append("This retrieval layer returns source/topic evidence only; full legal/cap calculations require dedicated intelligence modules.")

    return {
        "athena_version": ATHENA_VERSION,
        "knowledge_domain": "public_hockey",
        "query": query,
        "mode": mode,
        "status": status,
        "confidence": round(confidence, 3),
        "packs_checked": len(packs),
        "evidence_count": len(evidence),
        "evidence": evidence,
        "limitations": limitations,
    }


def build_public_hockey_scout_answer(
    question: str,
    project_root: Optional[Path] = None,
    mode: str = "public_sports",
) -> Dict[str, Any]:
    """Build a bounded Scout-style answer from retrieved knowledge-pack evidence."""
    retrieval = retrieve_public_hockey_knowledge(question, project_root=project_root, mode=mode, limit=5, auto_build=False)
    evidence = retrieval.get("evidence", [])
    if evidence:
        labels = ", ".join(f"{item['label']} ({'; '.join(item.get('authority_refs', []) or [])})" for item in evidence[:3])
        conclusion = f"Athena found public hockey knowledge-pack evidence relevant to this question: {labels}."
        observed = [
            f"{item['label']}: {item['summary']} Source: {item['source_title']} — {('; '.join(item.get('authority_refs', []) or ['registered topic']))}."
            for item in evidence[:5]
        ]
        title = "Public hockey knowledge"
    else:
        conclusion = "Athena could not find a matching public hockey knowledge-pack topic for this question."
        observed = [f"Packs checked: {retrieval.get('packs_checked', 0)}."]
        title = "Public hockey knowledge unavailable"

    return {
        "title": title,
        "confidence": retrieval.get("confidence", 0.0),
        "conclusion": conclusion,
        "observed_facts": observed,
        "known_limitations": retrieval.get("limitations", []),
        "developer_trace": {
            "question": question,
            "mode": mode,
            "retrieval_status": retrieval.get("status"),
            "packs_checked": retrieval.get("packs_checked"),
            "evidence_used": evidence,
        },
    }


def write_public_hockey_retrieval_report(
    query: str,
    project_root: Optional[Path] = None,
    mode: str = "public_sports",
) -> Dict[str, str]:
    """Write JSON/TXT retrieval outputs for debugging."""
    root = _project_root(project_root)
    retrieval = retrieve_public_hockey_knowledge(query, root, mode=mode, limit=10, auto_build=False)
    output_dir = root / "Output"
    reports_dir = root / "Reports"
    output_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)
    slug = re.sub(r"[^a-z0-9]+", "_", query.lower()).strip("_")[:60] or "query"
    json_path = output_dir / f"public_hockey_retrieval_{slug}.json"
    txt_path = reports_dir / f"public_hockey_retrieval_{slug}.txt"
    json_path.write_text(json.dumps(retrieval, indent=2, ensure_ascii=False), encoding="utf-8")

    lines = [
        "Public Hockey Knowledge Retrieval",
        "=================================",
        f"Athena: {retrieval['athena_version']}",
        f"Query: {retrieval['query']}",
        f"Mode: {retrieval['mode']}",
        f"Status: {retrieval['status']}",
        f"Confidence: {retrieval['confidence']}",
        f"Evidence: {retrieval['evidence_count']}",
        "",
    ]
    for item in retrieval.get("evidence", []):
        lines.append(f"- {item['label']} [{item['topic_key']}]")
        lines.append(f"  Source: {item['source_title']}")
        lines.append(f"  Authority refs: {'; '.join(item.get('authority_refs', []) or [])}")
        lines.append(f"  Summary: {item['summary']}")
        lines.append("")
    if retrieval.get("limitations"):
        lines.append("Limitations")
        lines.append("-----------")
        for limitation in retrieval["limitations"]:
            lines.append(f"- {limitation}")
    txt_path.write_text("\n".join(lines), encoding="utf-8")
    return {"json": str(json_path), "text": str(txt_path)}


