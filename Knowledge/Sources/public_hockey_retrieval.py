"""Deterministic retrieval over compact public hockey knowledge packs.

Athena does not reason directly from NHL/NHLPA source PDFs at runtime. This
module retrieves bounded evidence from compact JSON knowledge packs generated by
``public_hockey_packs.py`` and returns evidence records that Scout can expose in
public-sports mode or fantasy mode.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple
import json
import re

